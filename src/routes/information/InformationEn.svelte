    <h2>What is Mass Driver?</h2>
    <p>
      An app that makes posting to Bluesky easier.<br />
      It is packed with features for everyday posting, such as posting to multiple accounts at once and automatic image resizing.
    </p>
  </section>

  <section class="info-quick-start">
    <h2>Getting started (3 steps)</h2>
    <ol class="info-steps">
      <li>
        <strong>Create an app password</strong>
        <span>For safety, create a dedicated password in Bluesky's <a href="https://bsky.app/settings/app-passwords" target="_blank" rel="noreferrer">settings</a> instead of using your regular password.</span>
      </li>
      <li>
        <strong>Log in</strong>
        <span>Enter the password you created and your handle (e.g. <code>shino3.bsky.social</code>) to log in.</span>
      </li>
      <li>
        <strong>Pick accounts and Lift Off!</strong>
        <span>Just choose the accounts to post to and post. You can also post to multiple accounts at the same time.</span>
      </li>
    </ol>
    <div class="info-quick-start-cta">
      <a href="/login" class="btn btn-primary">Go to login</a>
    </div>
  </section>

  <section class="info-section">
    <h2>Handy features</h2>

    <h3>Post to multiple accounts at once</h3>
    <p>
      You can register multiple accounts on the "Account" screen. Just check the accounts when posting, and the same content is posted to all of them.
    </p>

    <h3>Automatic image resizing</h3>
    <p>
      You can attach up to 4 images. They are automatically resized and compressed to fit Bluesky's limits (1MB / 2000px), so you can upload without worrying about file size.
    </p>

    <h3>Rich text</h3>
    <ul>
      <li>Start with <code>@</code> to mention a user</li>
      <li>Enter a URL to create a link card automatically</li>
      <li>Start with <code>#</code> to make it a hashtag</li>
    </ul>

    <h3>Hashtag history &amp; templates</h3>
    <p>
      Hashtags you have used are remembered below the post box, and you can insert them with one tap.<br />
      You can also save greetings and phrases you use often as "templates" and call them up any time.
    </p>

    <h3>All notifications in one place</h3>
    <p>
      Check notifications for all your registered accounts on a single screen. You can also filter by replies, likes, and more.
    </p>
  </section>

  <section class="info-section">
    <h2>Sharing from your phone and other apps</h2>
    <p>
      Choose "Add to Home Screen" or "Install app" from your browser menu to use it like a smartphone app.
    </p>
    <ul>
      <li><strong>Android and PC (Chrome / Edge):</strong> Pick "Mass Driver" from the OS share menu to send the URL or text of the page you are viewing straight to the compose screen. You can also send images directly from the share menu of your photo or camera app (up to 4).</li>
      <li><strong>iOS (Safari):</strong> Sending directly from the share menu (text or images) is not supported. Add images with the camera button or the image button on the compose screen. For text, you can use the "share URL" feature (a link with <code>?intent=</code>) to open the compose screen from things like a blog's share button.</li>
    </ul>
  </section>

  <section class="info-section">
    <h2>Your data stays with you</h2>
    <p>
      Login information such as passwords, and saved templates, are all stored <strong>only on your device (in your browser)</strong>.<br />
      Your data is never sent to a Mass Driver server, so you can use it with peace of mind.<br />
      <small>* Clearing your browser history or data will log you out automatically.</small>
    </p>
  </section>

